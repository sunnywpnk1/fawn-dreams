export const DEFAULT_FRAME_ID = 'bleu-ancien';

export const FRAME_TABS: FrameFilterTab[] = ['All', 'Vintage', 'Romantic', 'Film', 'Minimal', 'Premium'];

export const getFrame = (id: string | null | undefined) =>
  FRAMES.find((f) => f.id === id) ?? FRAMES.find((f) => f.id === DEFAULT_FRAME_ID)!;

export function frameMatchesTab(frame: FrameDesign, tab: FrameFilterTab) {
  if (tab === 'All') return true;
  if (tab === 'Premium') return frame.premium || frame.category === 'Premium';
  return frame.category === tab;
}
